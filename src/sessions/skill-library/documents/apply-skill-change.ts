import { mkdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { parseFrontmatter } from "@earendil-works/pi-coding-agent";
import { WireError } from "../../../gateway/wire/create-error.ts";
import type { SkillLibraryContext, SkillLibraryEntry, SkillManageRequest } from "../skill-types.ts";
import { validateSkillChange } from "../tools/validate-skill-change.ts";
import { SKILL_SECTIONS } from "../skill-constants.ts";
import { age } from "../lifecycle/age-records.ts";
import { path as resolveOwnedPath } from "./resolve-owned-path.ts";
import { remove } from "../lifecycle/remove-skill.ts";
import { publish } from "../lifecycle/publish-records.ts";
import { setScope } from "../lifecycle/set-scope.ts";
import { sectionBody } from "./format-section.ts";
import { document } from "./serialize-document.ts";
import { replaceSection } from "./replace-section.ts";
import { frontmatter as parseSkillFrontmatter } from "./parse-frontmatter.ts";
import { bound } from "../lifecycle/enforce-capacity.ts";
import { list } from "../catalog/list.ts";

export function manage(ctx: SkillLibraryContext, input: SkillManageRequest): { skill: SkillLibraryEntry } | { deleted: string } {
  const request = validateSkillChange(input);
  age(ctx);
  const path = resolveOwnedPath(ctx, request.name, request.action === "write_file" || request.action === "remove_file" ? request.path : "SKILL.md");
  const existing = ctx.records.find((item) => item.name === request.name);
  if (request.action === "create") {
    if (existing) throw new Error(`Shared skill ${JSON.stringify(request.name)} already exists; use patch instead${existing.status === "archived" ? " after restoring it" : ""}.`);
  } else {
    if (!existing) throw new WireError("NOT_FOUND", "The shared skill does not exist.");
    if (request.action === "delete") {
      remove(ctx, existing);
      publish(ctx);
      return { deleted: request.name };
    }
    if (existing.status === "archived") throw new Error("Restore the archived skill before editing it.");
  }
  if (request.action === "patch" && request.section === "scope") return { skill: setScope(ctx, request.name, request.value).find((entry) => entry.name === request.name)! };
  if ((request.action === "write_file" || request.action === "remove_file") && request.path.split("/").at(-1) === "SKILL.md") throw new Error("SKILL.md is generated by create/patch only; use delete to remove the whole skill.");
  if (request.action === "remove_file") unlinkSync(path);
  else {
    let content: string;
    if (request.action === "create") {
      const { name, description, whenToUse, evidence } = request;
      const body = (Object.keys(SKILL_SECTIONS) as (keyof typeof SKILL_SECTIONS)[]).map((section) => `## ${SKILL_SECTIONS[section]}\n\n${sectionBody(section, request[section])}`).join("\n\n");
      content = document({ name, description, "when-to-use": whenToUse, evidence }, body);
    } else if (request.action === "patch") {
      const previous = readFileSync(path, "utf8");
      const parsed = parseFrontmatter(previous);
      let body = parsed.body;
      if (request.section !== "description") body = replaceSection(body, request.section, request.value);
      if (request.section === "description" || request.section === "whenToUse" || request.section === "evidence") parsed.frontmatter[request.section === "whenToUse" ? "when-to-use" : request.section] = request.value;
      content = document(parsed.frontmatter, body);
    } else content = request.content;
    if (request.action !== "write_file") parseSkillFrontmatter(ctx, request.name, content);
    mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
    writeFileSync(path, content, { mode: 0o600 });
  }
  const now = new Date(ctx.now()).toISOString();
  if (existing) existing.changedAt = now;
  else if (request.action === "create") ctx.records.push({ name: request.name, scope: request.scope, status: "staging", manual: false, promotionReady: false, sessions: [], createdAt: now, changedAt: now });
  bound(ctx); publish(ctx);
  return { skill: list(ctx).find((entry) => entry.name === request.name)! };
}
