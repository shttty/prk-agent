import assert from "node:assert/strict";
import { mkdir, readFile, readdir } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { withThemeWorkbench } from "../fixtures/theme-workbench.mjs";
import { builtinThemes } from "../../shared/themes.js";

const evidence = process.env.PI_TEST_WEB_EVIDENCE;
if (evidence) await mkdir(evidence, { recursive: true });
const { chromium } = await import(pathToFileURL(resolve(process.env.PI_TEST_PLAYWRIGHT)).href);
await withThemeWorkbench(async ({ root, url, apiUrl, sessionId: worker, onCleanup }) => {
  const browser = await chromium.launch({ executablePath: process.env.PI_TEST_CHROMIUM, headless: true, ignoreDefaultArgs: ["--hide-scrollbars"], args: ["--no-sandbox"] });
  onCleanup(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: "light" });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const openSettings = async (page) => {
    if (await page.locator("#open-sidebar").isVisible()) await page.locator("#open-sidebar").click();
    await page.locator("#open-settings").click();
    await page.locator("#open-general").click();
    await page.locator("#settings-theme").waitFor();
    await page.evaluate(async () => { await document.fonts.ready; await Promise.all(document.getAnimations().filter((animation) => animation.effect?.getComputedTiming().iterations !== Infinity).map((animation) => animation.finished.catch(() => {}))); });
  };
  const importPreview = async (theme) => {
    await page.locator("#theme-json").fill(JSON.stringify(theme));
    await page.locator("#theme-preview").click();
    await page.locator("#theme-save").waitFor();
  };
  const custom = { name: "Theme acceptance", mode: "light", tokens: { "--pi-bg": "#faf4eb", "--pi-ink": "#102030", "--pi-accent": "#885599", "--pi-code-bg": "#faf4eb", "--pi-syn-comment": "#faf4eb", "--pi-syn-keyword": "#5544aa", "--pi-tree": "#e6dccb" } };
  await page.goto(url);
  await page.locator(`[data-session-id="${worker}"] .management-session-select`).click();
  await page.locator("#composer").fill("Render the controlled theme sample.");
  await page.locator("#send-message").click();
  await page.locator('.pi-tool[data-state="done"]').waitFor({ state: "attached" });
  await openSettings(page);
  assert.equal(await page.locator("#theme-delete").count(), 0);
  const baseline = await page.evaluate(() => getComputedStyle(document.body).color);
  for (const [key, value] of [["--pi-not-a-token", "red"], ["--pi-ink", "invalid-color"], ["--pi-font-ui", "red"], ["--pi-ink", "rgb(NaN 2 3)"]]) {
    await page.locator("#theme-json").fill(JSON.stringify({ ...custom, tokens: { [key]: value } }));
    await page.locator("#theme-preview").click();
    await page.locator(`#theme-error[data-key="${key}"]`).waitFor();
    assert.equal(await page.locator("#theme-save").count(), 0);
  }
  await importPreview(custom);
  assert.equal(Number(await page.locator('#theme-aa-warnings [data-pair="comment"]').getAttribute("data-ratio")), 1);
  assert.equal(await page.locator("#theme-preview-sample").evaluate((node) => getComputedStyle(node).color), "rgb(16, 32, 48)");
  await page.locator("#theme-save").click();
  await page.waitForFunction(() => getComputedStyle(document.body).color === "rgb(16, 32, 48)");
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--pi-tree").trim()), "#e6dccb", "the file-tree token is importable and applied");
  const id = await page.locator("#settings-theme").inputValue();
  assert.notEqual(baseline, "rgb(16, 32, 48)");
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--pi-muted").trim()), builtinThemes[0].tokens["--pi-muted"]);
  assert.deepEqual(JSON.parse(await readFile(join(root, "themes", `${id}.json`), "utf8")), custom);
  await page.reload();
  await page.waitForFunction(() => getComputedStyle(document.body).color === "rgb(16, 32, 48)");
  await openSettings(page);
  assert.equal(await page.locator("#settings-theme").inputValue(), id);
  const downloadEvent = page.waitForEvent("download");
  await page.locator("#theme-export").click();
  const download = await downloadEvent;
  const exported = JSON.parse(await readFile(await download.path(), "utf8"));
  assert.deepEqual(exported, custom);
  await page.locator("#theme-file").setInputFiles({ name: "roundtrip.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(exported)) });
  await page.locator("#theme-save").waitFor();
  await page.locator("#theme-save").click();
  await page.waitForFunction((first) => document.querySelector("#settings-theme").value !== first, id);
  const duplicate = await page.locator("#settings-theme").inputValue();
  assert.deepEqual(JSON.parse(await readFile(join(root, "themes", `${duplicate}.json`), "utf8")), custom);
  await page.locator("#theme-delete").click();
  await page.locator("#theme-cancel-delete").click();
  assert((await readdir(join(root, "themes"))).includes(`${duplicate}.json`));
  await page.locator("#theme-delete").click();
  await page.locator("#theme-confirm-delete").click();
  await page.waitForFunction(() => document.querySelector("#settings-theme").value === "builtin-light");
  assert(!(await readdir(join(root, "themes"))).includes(`${duplicate}.json`));
  assert.equal(await page.locator("#theme-delete").count(), 0);
  for (const scheme of ["light", "dark"]) {
    await page.locator("#settings-theme").selectOption(`builtin-${scheme}`);
    await page.waitForFunction((mode) => document.documentElement.dataset.mantineColorScheme === mode, scheme);
    if (evidence) await page.screenshot({ path: join(evidence, `themes-desktop-${scheme}.png`) });
  }
  const builtinDownload = page.waitForEvent("download");
  await page.locator("#theme-export").click();
  const { name: builtinName, mode: builtinMode, tokens: builtinTokens } = builtinThemes[1];
  assert.deepEqual(JSON.parse(await readFile(await (await builtinDownload).path(), "utf8")), { name: builtinName, mode: builtinMode, tokens: builtinTokens });
  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, colorScheme: "dark", isMobile: true, hasTouch: true });
  const mobile = await phone.newPage();
  mobile.on("pageerror", (error) => errors.push(error.message));
  await mobile.goto(url);
  await openSettings(mobile);
  await mobile.locator(`#settings-theme option[value="${id}"]`).waitFor({ state: "attached" });
  assert.equal(await mobile.locator("#settings-theme").inputValue(), "auto", "selection is device-local while library is shared");
  assert.equal(await mobile.evaluate(() => document.documentElement.dataset.mantineColorScheme), "dark");
  if (evidence) await mobile.screenshot({ path: join(evidence, "themes-phone-dark.png") });
  assert(await mobile.locator("#theme-settings").evaluate((node) => node.scrollWidth <= node.clientWidth + 1), "phone controls fit");
  await mobile.locator("#settings-theme").selectOption(id);
  await mobile.waitForFunction(() => getComputedStyle(document.body).color === "rgb(16, 32, 48)");
  await mobile.reload();
  await mobile.waitForFunction(() => getComputedStyle(document.body).color === "rgb(16, 32, 48)");
  await phone.close();
  const post = (path, body) => fetch(`${apiUrl}/api/themes/${path}`, { method: "POST", headers: { Origin: apiUrl, "Content-Type": "application/json" }, body: JSON.stringify(body) });
  assert.equal((await post("delete", { id: "builtin-light", confirm: true })).status, 400);
  const rejected = await post("import", { theme: { ...custom, tokens: { "--pi-ink": "not-a-color" } } });
  assert.equal(rejected.status, 400);
  assert.equal((await rejected.json()).details.key, "--pi-ink");
  await page.locator("#settings-theme").selectOption(id);
  await page.locator("#close-settings").click();
  await page.locator("details.pi-turn-process > summary").first().click();
  await page.locator(".pi-tool > summary").first().click();
  const expansion = page.locator('[data-action="expand-lines"]').first();
  await expansion.click();
  await page.locator(".pi-tool .tok-keyword").first().waitFor();
  assert.equal(await page.locator(".pi-tool .tok-keyword").first().evaluate((node) => getComputedStyle(node).color), "rgb(85, 68, 170)");
  await openSettings(page);
  await page.locator("#theme-delete").click();
  await page.locator("#theme-confirm-delete").click();
  await page.waitForFunction(() => document.querySelector("#settings-theme").value === "builtin-light");
  assert.deepEqual(await readdir(join(root, "themes")), []);
  await page.locator("#close-settings").click();
  await page.locator("#theme-toggle").click();
  await page.waitForFunction(() => document.documentElement.dataset.mantineColorScheme === "dark");
  await openSettings(page);
  await page.locator("#settings-theme").selectOption("auto");
  await page.emulateMedia({ colorScheme: "light" });
  await page.waitForFunction(() => document.documentElement.dataset.mantineColorScheme === "light");
  assert.deepEqual(errors, []);
  console.log("PASS themes: real Gateway/Vite/Chromium; import, preview, AA advisory, CSS/syntax, refresh, roundtrip, shared library/device selection, deletion and builtin protection");
});
