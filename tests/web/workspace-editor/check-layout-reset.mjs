import assert from "node:assert/strict";
import { createMockFs } from "../../fixtures/workspace-mock/create-mock-fs.mjs";
import { selectSession } from "../../fixtures/workspace-mock/select-session.mjs";
import { decodeLayoutCode, layoutStorage as seed, openFromLayoutCode } from "../../fixtures/layout-code.mjs";
import { LAYOUT } from "../../../web/shell/layout/layout-store.js";
import { gridKey, layoutKey } from "../../../web/shell/layout/layout-store.js";

export async function checkLayoutReset(ctx) {
await ctx.step("reset layout: default stage open, file order, selection, unsaved text and shells kept", async () => {
    const h = await ctx.open({ viewport: { width: 1440, height: 860 }, storage: ctx.OPEN, colorScheme: "dark", terminals: [] });
    const { page } = h;
    await ctx.messUp(page);
    const tabOrder = () => page.locator("#desktop-stage .pi-tab").evaluateAll((nodes) => nodes.map((node) => [node.dataset.kind, node.dataset.path ?? node.dataset.shell]));
    const before = await tabOrder();
    const active = await page.locator("#desktop-stage .dv-active-group .dv-active-tab .pi-tab").getAttribute("data-shell");
    const keysBefore = await page.evaluate(() => Object.keys(localStorage).sort());
    const layoutKeys = Object.keys(LAYOUT).map(layoutKey);
    const layoutDocuments = [gridKey("w1"), "pi.layout.presets"];
    for (const key of keysBefore) assert.ok(layoutKeys.includes(key) || layoutDocuments.includes(key) || ["pi.files.showHidden", "pi-session-theme", "pi-session-color-theme"].includes(key), `every saved key is registered layout or known non-layout: ${key}`);
    await page.locator("#open-settings").click();
    await page.locator("#reset-layout").click();
    await page.locator('#settings-status[data-status="reset"]').waitFor();
    await page.keyboard.press("Escape");
    assert.deepEqual(await page.evaluate((keys) => keys.filter((key) => localStorage.getItem(key) !== null), layoutKeys), [layoutKey("workspaceOpen")], "reset clears saved scalar overrides except the open workspace");
    const fresh = async (label) => {
      const defaults = { ...LAYOUT, workspaceOpen: true };
      const differs = await page.evaluate((values) => Object.entries(values).filter(([key, value]) => localStorage.getItem(key) !== null && localStorage.getItem(key) !== value).map(([key]) => key), Object.fromEntries(Object.entries(defaults).map(([name, value]) => [layoutKey(name), JSON.stringify(value)])));
      assert.deepEqual(differs, [], `${label}: saved scalars are defaults with workspace open`);
      ctx.near(await ctx.width(page, ".desktop-sidebar"), LAYOUT.sessionWidth, `${label}: session sidebar default width`);
      assert.equal(await ctx.stageOpen(page), true, `${label}: workspace open`);
    };
    await fresh("after reset");
    assert.equal(await page.locator('#desktop-stage .pi-term[data-shell="shell"] .xterm').getAttribute("data-mark"), "kept", "the xterm was not rebuilt");
    assert.equal(await page.evaluate(() => [localStorage.getItem("pi.files.showHidden"), document.documentElement.dataset.mantineColorScheme].join()), "1,dark", "non-layout preferences untouched");
    const reset = await ctx.widthsHold(page, "after reset");
    assert.equal(await ctx.groups(page), 2, "chat and one workspace group remain");
    assert.ok(reset.chat.right < reset.work[0].left, "the workspace group sits right of chat");
    ctx.near(reset.work[0].width, 514, "the workspace returns to its default card width");
    assert.deepEqual(await tabOrder(), before, "reset preserves every tab's order");
    assert.equal(await page.locator("#desktop-stage .dv-active-group .dv-active-tab .pi-tab").getAttribute("data-shell"), active, "reset preserves the selected tab");
    assert.deepEqual((await page.locator(".pi-tab[data-path]").evaluateAll((nodes) => nodes.map((node) => node.dataset.path))).sort(), ["README.md", "main.py", "notes.txt"], "every file is still open");
    assert.equal(await ctx.tab(page, "main.py").getAttribute("data-dirty"), "true", "the unsaved tab is still unsaved");
    assert.deepEqual(await page.locator('#desktop-stage .pi-tab[data-kind="terminal"]').evaluateAll((nodes) => nodes.map((node) => node.dataset.shell).sort()), ["shell", "shell-2"], "both shells are tabs of the workspace group");
    await page.locator("#toggle-tree").click();
    ctx.near(await ctx.width(page, "#file-tree"), LAYOUT.treeWidth, "directory popover default width");
    await page.locator("#toggle-tree").click();
    await ctx.tab(page, "main.py").click();
    assert.match(await (await ctx.editor(page, "main.py")).textContent(), /# unsaved/, "the unsaved text is still there");
    assert.equal(await page.locator('#desktop-stage .pi-term[data-shell="shell"] .xterm').getAttribute("data-mark"), "kept");
    assert.equal(await page.locator('#desktop-stage .pi-term[data-shell="shell-2"] .xterm').count(), 1, "the second shell is mounted too");
    await page.reload(); await selectSession(page, "w1");
    await ctx.tab(page, "main.py").waitFor();
    await fresh("after reload");
    await ctx.finish(h, "reset");
    const cold = await ctx.open({ viewport: { width: 1440, height: 860 }, storage: ctx.OPEN });
    await ctx.openFile(cold.page, "main.py"); await ctx.openFile(cold.page, "README.md");
    await ctx.dragToRightEdge(cold.page, "README.md");
    await ctx.toggleWorkspace(cold.page, false, "saved reset: collapse");
    await cold.page.reload(); await selectSession(cold.page, "w1");
    await cold.page.locator("#open-settings").click();
    await cold.page.locator("#reset-layout").click();
    await cold.page.locator('#settings-status[data-status="reset"]').waitFor();
    await cold.page.keyboard.press("Escape");
    await cold.page.locator('#desktop-stage[data-open="true"]').waitFor();
    await ctx.tab(cold.page, "README.md").waitFor();
    assert.equal(await ctx.groups(cold.page), 2, "a saved split resets to chat and one workspace group");
    await ctx.finish(cold, "saved reset");
  });

await ctx.step("layout code: export -> decode -> write back -> same layout", async () => {
    const h = await ctx.open({ viewport: { width: 1440, height: 860 }, storage: ctx.OPEN, terminals: [] });
    const { page, context } = h;
    await context.grantPermissions(["clipboard-read", "clipboard-write"], { origin: ctx.server.url });
    await ctx.messUp(page);
    const taken = await ctx.boxes(page);
    await page.locator("#open-settings").click();
    await page.locator("#copy-layout-code").click();
    await page.locator('#settings-status[data-status="copied"]').waitFor();
    const code = await page.evaluate(() => navigator.clipboard.readText());
    const decoded = decodeLayoutCode(code);
    assert.deepEqual(Object.keys(decoded.layout).sort(), Object.keys(LAYOUT).sort(), "every layout value");
    assert.equal(decoded.grid.sessionId, "w1", "the exported grid identifies its session");
    assert.equal(decoded.grid.value.panels["stage:chat"].contentComponent, "chat", "the exported grid includes chat");
    assert.deepEqual([decoded.context.viewport, decoded.context.breakpoint, decoded.context.session, decoded.context.filesOpen, "terminalShown" in decoded.context], [{ width: 1440, height: 860 }, "desktop", "session", true, false]);
    assert.ok(!code.includes("unsaved") && !JSON.stringify(decoded).includes("unsaved"), "no file content");
    await ctx.finish(h, "code taken");
    const replay = await openFromLayoutCode(ctx.browser, ctx.server.url, code, { fs: createMockFs(ctx.FILES) });
    ctx.openOnes.push(replay.context);
    await selectSession(replay.page, "w1");
    await ctx.tab(replay.page, "main.py").waitFor();
    const again = await ctx.boxes(replay.page);
    for (const key of ["side", "chat", "tree"]) ctx.near(again[key]?.width ?? 0, taken[key]?.width ?? 0, `replayed ${key} width`);
    assert.equal(again.work.length, taken.work.length, "the exported split groups return");
    again.work.forEach((group, i) => { for (const key of ["left", "top", "width", "height"]) ctx.near(group[key], taken.work[i][key], `replayed workspace group ${i} ${key}`); });
    await ctx.finish(replay, "code replay", false);
    // no clipboard (plain-http page): the code is shown to select by hand
    const manual = replay;
    await ctx.restart(manual, {}, "w1", { width: 1280, height: 860 });
    await manual.page.evaluate(() => { Object.defineProperty(navigator, "clipboard", { value: undefined }); });
    await manual.page.locator("#open-settings").click();
    await manual.page.locator("#copy-layout-code").click();
    const shown = await manual.page.locator("#layout-code").inputValue();
    assert.equal(decodeLayoutCode(shown).context.viewport.width, 1280, "the shown code decodes");
    await ctx.finish(manual, "code manual");
  });
}
