import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { rm, writeFile } from "node:fs/promises";

export async function checkStreamScenarios(ctx) {
  const { scenario, create, open, visibleUi, screenshot, stop, until, stage, launch, initialPid, socket, oldAnswer, streamOwnership, answer, transport, invoke, streaming, sleep, select, state } = ctx;
  await scenario("restart", async (result, check) => {
    const previous = await create("restart-old", 80);
    await open(previous.sessionId);
    await visibleUi(previous);
    const marker = randomUUID();
    await ctx.page.evaluate((value) => { window.prkRestartDocument = value; }, marker);
    let navigations = 1;
    ctx.page.on("load", () => { navigations++; });
    let heldStreams = 0;
    let holdReconnect = true;
    const reconnectGate = new Promise((resolve) => { ctx.releaseReconnect = resolve; });
    await ctx.page.route("**/api/**/events", async (route) => { if (holdReconnect) { heldStreams++; await reconnectGate; } await route.continue(); });
    await screenshot("restart-before");
    await ctx.client.disconnect(); ctx.client = undefined;
    await stop("SIGKILL");
    await rm(socket, { force: true });
    await until(() => heldStreams, (count) => count > 0, "automatic EventSource reconnect request", 15000);
    await stage("restart-new", 1);
    const replacementPid = await launch("new", false);
    assert.notEqual(replacementPid, initialPid);
    await ctx.client.request("recoverSession", { sessionId: previous.sessionId, mode: "new", target: "stream" });
    const snapshot = await state(previous.sessionId);
    const replacement = { snapshot, prompt: snapshot.extensionUi.prompts.find((prompt) => prompt.kind === "confirm"), status: snapshot.extensionUi.status.find((entry) => entry.key === "stream-proof").text };
    assert(replacement.prompt, "Replacement extension creates a confirm before transport resumes");
    assert.notEqual(replacement.prompt.id, previous.prompt.id);
    assert.equal(snapshot.sessionId, previous.snapshot.sessionId);
    assert(snapshot.extensionUi.revision < previous.snapshot.extensionUi.revision, "Counter really restarts below the old UI revision");
    Object.assign(result, { sessionId: previous.sessionId, oldSnapshot: previous.snapshot, newSnapshot: snapshot, heldStreams });
    holdReconnect = false; ctx.releaseReconnect();
    await oldAnswer(previous.sessionId, previous, replacement, result, check);
    await check("automatic EventSource reconnect adopts replacement host UI", () => visibleUi(replacement));
    await check("old confirm retired", async () => assert.equal(await ctx.page.locator(`[data-prompt-id="${previous.prompt.id}"]`).count(), 0));
    await check("same unrefreshed document", async () => { assert.equal(await ctx.page.evaluate((value) => window.prkRestartDocument === value, marker), true); assert.equal(navigations, 1); });
    await check("new stream identity", () => { assert.equal(typeof snapshot.streamId, "string"); assert(snapshot.streamId); assert.notEqual(snapshot.streamId, previous.snapshot.streamId); });
    await check("restart snapshot, events and render share stream ownership", () => streamOwnership(previous.sessionId, snapshot));
    await check("new browser answer reaches new extension", () => answer(replacement));
  });

  await scenario("reload", async (result, check) => {
    const previous = await create("reload-old", 80);
    await open(previous.sessionId);
    await visibleUi(previous);
    const marker = randomUUID();
    await ctx.page.evaluate((value) => { window.prkReloadDocument = value; }, marker);
    await ctx.page.locator("#composer").fill("RELOAD_DRAFT_保存");
    await screenshot("reload-before");
    await stage("reload-new", 1);
    await ctx.page.locator(`[data-session-id="${previous.sessionId}"] [data-action="session-menu"]`).click();
    const response = ctx.page.waitForResponse((response) => response.request().method() === "POST" && response.url().endsWith(`/api/sessions/${previous.sessionId}/native`) && response.request().postDataJSON().action === "reload");
    await ctx.page.locator("#reload-session").click();
    const reloadResponse = await response;
    assert.equal(reloadResponse.status(), 200);
    assert.equal((await reloadResponse.json()).status, "completed", "Actual product reload control must complete");
    const snapshot = await state(previous.sessionId);
    const replacement = { snapshot, prompt: snapshot.extensionUi.prompts.find((prompt) => prompt.kind === "confirm"), status: snapshot.extensionUi.status.find((entry) => entry.key === "stream-proof").text };
    assert(replacement.prompt);
    assert.notEqual(replacement.prompt.id, previous.prompt.id);
    assert.equal(snapshot.sessionId, previous.snapshot.sessionId);
    assert(snapshot.extensionUi.revision < previous.snapshot.extensionUi.revision, "Reload really restarts UI revision");
    Object.assign(result, { sessionId: previous.sessionId, oldSnapshot: previous.snapshot, newSnapshot: snapshot });
    await oldAnswer(previous.sessionId, previous, replacement, result, check);
    await check("reload adopts replacement UI", () => visibleUi(replacement));
    await check("reload retires old confirm", async () => assert.equal(await ctx.page.locator(`[data-prompt-id="${previous.prompt.id}"]`).count(), 0));
    await check("reload keeps document and draft", async () => { assert.equal(await ctx.page.evaluate((value) => window.prkReloadDocument === value, marker), true); assert.equal(await ctx.page.locator("#composer").inputValue(), "RELOAD_DRAFT_保存"); });
    await check("reload changes stream identity", () => { assert.equal(typeof snapshot.streamId, "string"); assert(snapshot.streamId); assert.notEqual(snapshot.streamId, previous.snapshot.streamId); });
    await check("reload snapshot, events and render share stream ownership", () => streamOwnership(previous.sessionId, snapshot));
    await check("replacement reload confirm works", () => answer(replacement));
  });

  await scenario("reorder", async (result, check) => {
    const current = await create("reorder");
    await open(current.sessionId);
    await visibleUi(current);
    await answer(current);
    const start = transport.frames.length;
    transport.hold((frame) => frame.sessionId === current.sessionId && frame.event === "host" && frame.data.type === "extension_ui" && frame.data.details?.extensionUi?.status.some((item) => item.key === "stream-proof" && item.text === "ORDER_OLD"));
    await invoke(current.sessionId, "/stream-status ORDER_OLD");
    const delayedUi = transport.frames.slice(start).find((frame) => frame.sessionId === current.sessionId && frame.event === "host" && frame.data.type === "extension_ui" && frame.data.details?.extensionUi?.status.some((item) => item.text === "ORDER_OLD"));
    assert(delayedUi, "Transport must record and hold an actual old extension frame");
    transport.release();
    await invoke(current.sessionId, "/stream-status ORDER_NEW");
    await ctx.page.waitForFunction(() => document.querySelector('[data-status-key="stream-proof"]')?.textContent === "ORDER_NEW");
    const latest = await state(current.sessionId);
    assert(delayedUi.data.details.extensionUi.revision < latest.extensionUi.revision);
    assert.equal(delayedUi.data.streamId, latest.streamId, "Revision ordering is tested within one actual identity");
    result.delayedUiFrameId = delayedUi.id;
    result.latestRevision = latest.extensionUi.revision;
    transport.replay(delayedUi);
    await sleep(250);
    await check("late old UI revision discarded", async () => { assert.equal(await ctx.page.locator('[data-status-key="stream-proof"]').textContent(), "ORDER_NEW"); assert.equal(Number(await ctx.page.locator("[data-extension-ui-revision]").getAttribute("data-extension-ui-revision")), latest.extensionUi.revision); });
    const beforeTool = transport.frames.length;
    transport.hold((frame) => frame.sessionId === current.sessionId && frame.event === "host" && frame.data.type === "state_changed" && frame.data.details?.state === "running");
    const running = await streaming(current.sessionId, "ORDER_STREAM");
    const delayedState = transport.frames.slice(beforeTool).find((frame) => frame.sessionId === current.sessionId && frame.event === "host" && frame.data.type === "state_changed" && frame.data.details?.state === "running");
    assert(delayedState, "Transport must record and hold an actual old state event");
    transport.release();
    await writeFile(running.release, "release");
    const completed = await until(() => state(current.sessionId), (value) => value.recentOperations.some((item) => item.operationId === running.accepted.operationId), "real ordering tool completion");
    await ctx.page.locator(`[data-session-id="${current.sessionId}"][data-status="idle"]`).waitFor();
    assert(delayedState.data.sequence < completed.sequence);
    assert.equal(delayedState.data.streamId, completed.streamId, "Sequence ordering is tested within one actual identity");
    result.delayedStateFrameId = delayedState.id;
    result.latestSequence = completed.sequence;
    transport.replay(delayedState);
    await sleep(250);
    await check("late old sequence cannot resurrect running state", async () => assert.equal(await ctx.page.locator(`.management-session-row[data-session-id="${current.sessionId}"]`).getAttribute("data-status"), "idle"));
    await check("late frames leave no prompts or banners", async () => { assert.equal(await ctx.page.locator("[data-prompt-id]").count(), 0); assert.equal(await ctx.page.locator("#connection-banner").count(), 0); });
  });

  await scenario("switch", async (result, check) => {
    const a = await create("switch-A");
    const b = await create("switch-B");
    const showLive = async (token) => {
      await ctx.page.locator('[data-tool-name="kernel_code"][data-state="running"]').waitFor({ state: "attached" });
      for (const fold of await ctx.page.locator(".pi-turn-process").all()) if (await fold.getAttribute("open") === null) await fold.locator("summary").first().click();
      await ctx.page.locator(".pi-message-assistant .pi-markdown").filter({ hasText: token }).first().waitFor({ state: "visible" });
      await ctx.page.locator('[data-tool-name="kernel_code"][data-state="running"]').waitFor({ state: "visible" });
      (result.visibleStreamTokens ??= []).push(token);
    };
    await open(a.sessionId);
    await visibleUi(a);
    await answer(a);
    const activeA = await streaming(a.sessionId, "LIVE_SESSION_A_唯一");
    await ctx.page.waitForFunction(() => document.querySelector("#messages")?.textContent.includes("LIVE_SESSION_A_唯一"));
    await ctx.page.locator('[data-tool-name="kernel_code"][data-state="running"]').waitFor({ state: "attached" });
    await showLive("LIVE_SESSION_A_唯一");
    await ctx.page.locator("#composer").fill("/__session_stream_unknown__");
    await ctx.page.locator("#send-message").click();
    await ctx.page.locator("#connection-banner").waitFor({ state: "visible" });
    const draft = "SESSION_A_DRAFT_保留";
    await ctx.page.locator("#composer").fill(draft);
    await screenshot("switch-A-before");
    await select(b.sessionId);
    await visibleUi(b);
    await check("B has no A UI, tools, streams, banner or draft", async () => {
      assert.equal(await ctx.page.locator(`[data-prompt-id="${a.prompt.id}"]`).count(), 0);
      assert.equal(await ctx.page.locator('[data-status-key="stream-proof"]').textContent(), b.status);
      assert.equal(await ctx.page.locator("[data-tool-key]").count(), 0);
      assert.equal((await ctx.page.locator("#messages").textContent()).includes("LIVE_SESSION_A_唯一"), false);
      assert.equal(await ctx.page.locator("#connection-banner").count(), 0);
      assert.equal(await ctx.page.locator("#composer").inputValue(), "");
    });
    await screenshot("switch-B-clean");
    await answer(b);
    const activeB = await streaming(b.sessionId, "LIVE_SESSION_B_唯一");
    await ctx.page.waitForFunction(() => document.querySelector("#messages")?.textContent.includes("LIVE_SESSION_B_唯一"));
    await ctx.page.locator('[data-tool-name="kernel_code"][data-state="running"]').waitFor({ state: "attached" });
    await showLive("LIVE_SESSION_B_唯一");
    await ctx.page.locator("#composer").fill("/__session_stream_unknown__");
    await ctx.page.locator("#send-message").click();
    await ctx.page.locator("#connection-banner").waitFor({ state: "visible" });
    await ctx.page.locator("#composer").fill("SESSION_B_DRAFT");
    await select(a.sessionId);
    await ctx.page.waitForFunction((status) => document.querySelector('[data-status-key="stream-proof"]')?.textContent === status, a.status);
    await check("A returns with its own draft and no B UI/stream/banner", async () => {
      assert.equal(await ctx.page.locator(`[data-prompt-id="${b.prompt.id}"]`).count(), 0);
      assert.equal((await ctx.page.locator("#messages").textContent()).includes("LIVE_SESSION_B_唯一"), false);
      assert.equal(await ctx.page.locator("#connection-banner").count(), 0);
      assert.equal(await ctx.page.locator("#composer").inputValue(), draft);
      const keys = await ctx.page.locator("[data-tool-key]").evaluateAll((nodes) => nodes.map((node) => node.dataset.toolKey));
      assert(keys.length > 0, "A still owns its real running tool");
      assert(keys.every((key) => key.startsWith(`${a.sessionId}:`)), "No B tool belongs to the returned A view");
    });
    Object.assign(result, { a: { sessionId: a.sessionId }, b: { sessionId: b.sessionId }, draft });
    await writeFile(activeA.release, "release");
    await writeFile(activeB.release, "release");
    await until(() => state(a.sessionId), (value) => value.recentOperations.some((item) => item.operationId === activeA.accepted.operationId), "A actual tool finishes");
    await until(() => state(b.sessionId), (value) => value.recentOperations.some((item) => item.operationId === activeB.accepted.operationId), "B actual tool finishes");
  });
}
