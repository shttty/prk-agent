import assert from "node:assert/strict";
import { join } from "node:path";
import { parseDiff } from "../../../web/chat/tool-text/parse-diff.js";

export async function checkLazyBrowserContent({ tool, page, ids, requests, openAncestors, bytes, rowCount, outputA, shots, expand, until, fullA, fullEdit, resultOf, snapshot, context, ui, select, pageerrors }) {
  await tool(page, ids.a).waitFor({ state: "attached" });
  assert.equal(requests.length, 0, "live results do not prefetch full content");
  const rowA = tool(page, ids.a);
  await openAncestors(rowA);
  await rowA.locator(":scope > summary").click();
  await rowA.locator('[data-action="expand-lines"]').first().waitFor();
  assert.equal(await rowA.getAttribute("data-content-state"), "preview");
  const output = rowA.locator(".output-block");
  assert.equal(Number(await output.getAttribute("data-total-bytes")), bytes(outputA));
  assert.equal(Number(await output.getAttribute("data-total-lines")), rowCount(outputA));
  assert.equal(requests.length, 0, "opening a tool row only exposes its preview");
  assert(!(await rowA.textContent()).includes("LAZY_A_FULL_TAIL_Ω"));
  await rowA.scrollIntoViewIfNeeded();
  assert.equal(await page.locator('html[data-mantine-color-scheme="light"]').count(), 1);
  await page.screenshot({ path: join(shots, "lazy-tool-collapsed-light.png"), fullPage: false });
  await expand(rowA);
  assert.equal(await rowA.getAttribute("data-content-state"), "loaded");
  await until(async () => (await output.textContent()) === outputA, "expanded output equals the full SDK text");
  assert.equal(requests.filter((url) => url.searchParams.get("toolCallId") === ids.a).length, 1, "input/output requests for one row are deduplicated");
  assert.equal(requests.at(-1).searchParams.has("sessionId"), false);
  assert.equal(await rowA.locator('[data-action="copy-code"], [data-action="copy-tool"]').count(), 0, "tools gain no copy button");
  await output.evaluate((node) => { const selection = window.getSelection(); const range = document.createRange(); range.selectNodeContents(node); selection.removeAllRanges(); selection.addRange(range); });
  await page.keyboard.press("Control+c");
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), outputA, "native browser selection copies the full expanded output");
  await page.evaluate(() => window.getSelection().removeAllRanges());
  await output.evaluate((node) => node.scrollIntoView({ block: "start" }));
  await page.screenshot({ path: join(shots, "lazy-tool-expanded-light.png"), fullPage: false });
  await rowA.locator(":scope > summary").click();
  await rowA.locator(":scope > summary").click();
  await expand(rowA);
  assert.equal(requests.filter((url) => url.searchParams.get("toolCallId") === ids.a).length, 1, "repeated expansion uses the session/call/version cache");
  const nested = fullA.result.nestedCalls.calls;
  assert.equal(nested.length, 2);
  assert.deepEqual(await rowA.locator('[data-name="lazy_inner"]').evaluateAll((nodes) => nodes.map((node) => ({ count: Number(node.dataset.count), status: node.dataset.status }))), [{ count: 2, status: "ok" }], "the hydrated result retains SDK nested summaries");
  const expectedDiff = parseDiff(fullEdit.result.details.diff);
  assert(expectedDiff.rows.length > 40);
  assert(resultOf(snapshot.messages, ids.edit).outputPreview, "large structured diff is lazy even with small display text");
  await expand(tool(page, ids.edit));
  const stat = tool(page, ids.edit).locator("[data-add][data-del]");
  assert.equal(Number(await stat.getAttribute("data-add")), expectedDiff.add);
  assert.equal(Number(await stat.getAttribute("data-del")), expectedDiff.del);
  assert.equal(await tool(page, ids.edit).locator(".pi-cl-diff .is-add").count(), expectedDiff.add);
  assert.equal(await tool(page, ids.edit).locator(".pi-cl-diff .is-del").count(), expectedDiff.del);
  // A fresh browser document has no hydrated B. Search must resolve content outside the preview, not silently miss it.
  const fresh = await context.newPage();
  await fresh.goto(ui.url);
  await select(fresh);
  assert.equal(requests.filter((url) => url.searchParams.get("toolCallId") === ids.b).length, 0, "reload/selection do not prefetch unseen B");
  await fresh.locator("#composer-add").click();
  await fresh.locator("#find-current-page").click();
  await fresh.locator("#transcript-search").fill("LAZY_B_FULL_TAIL_Ω");
  await fresh.locator('.pi-transcript-search[data-status="ready"][data-count="1"]').waitFor();
  assert.equal(requests.filter((url) => url.searchParams.get("toolCallId") === ids.b).length, 1, "explicit search fetches deferred full content");
  assert.equal(await fresh.locator('.pi-transcript-search[data-status="ready"]').count(), 1);
  await fresh.locator("#transcript-search").press("Escape");
  await expand(tool(fresh, ids.b));
  const renderedOutput = tool(fresh, ids.b).locator(".extension-tool-result");
  await renderedOutput.waitFor();
  assert((await renderedOutput.textContent()).includes("LAZY_B_FULL_TAIL_Ω"), "expanded plugin rendering receives full original result");
  assert.equal(requests.filter((url) => url.searchParams.get("toolCallId") === ids.b).length, 1, "search and explicit expansion share the same cache");
  assert.equal(pageerrors.length, 0, JSON.stringify(pageerrors));
}
