import assert from "node:assert/strict";

export async function checkOperations(files, context) {
  const root = context.cwd;
  const file = `${root}/empty.txt`;
  await files.create(context, { path: file, type: "file" });
  assert.equal((await files.read(context, file)).content, "");
  const source = "β\r\nline\n";
  const first = await files.write(context, { path: file, content: source, format: "text" });
  assert.equal((await files.read(context, file)).content, source);
  assert.match(first.last_modified, /^mtime:/u);
  await assert.rejects(files.write(context, { path: file, content: "bad", format: "text", expectedLastModified: "mtime:0" }), { code: "CONFLICT" });
  assert.equal((await files.read(context, file)).content, source);
  await files.write(context, { path: file, content: "new", format: "text", expectedLastModified: first.last_modified });
  const binary = Buffer.from([0, 1, 255, 128, 13, 10]);
  await files.create(context, { path: `${root}/binary`, type: "file", content: binary.toString("base64"), format: "base64" });
  const binaryRead = await files.read(context, `${root}/binary`);
  assert.equal(binaryRead.format, "base64");
  assert.deepEqual(Buffer.from(binaryRead.content, "base64"), binary);
  const notebook = "{\n  \"cells\": [], \"metadata\": {}, \"nbformat\": 4\n}\n";
  await files.create(context, { path: `${root}/raw.ipynb`, type: "file", content: notebook });
  const notebookRead = await files.read(context, `${root}/raw.ipynb`);
  assert.equal(notebookRead.type, "notebook");
  assert.equal(notebookRead.content, notebook);
  await files.create(context, { path: `${root}/dir`, type: "directory" });
  await files.create(context, { path: `${root}/dir/child`, type: "file", content: "in target" });
  await assert.rejects(files.delete(context, `${root}/dir`));
  assert.equal((await files.read(context, `${root}/dir/child`)).content, "in target");
  const copied = await files.copy(context, `${root}/dir`, root);
  assert.equal(copied.path, `${root}/dir-Copy1`);
  assert.equal((await files.read(context, `${copied.path}/child`)).content, "in target");
  const moved = await files.rename(context, file, `${root}/renamed.txt`);
  assert.equal(moved.path, `${root}/renamed.txt`);
  await assert.rejects(files.read(context, file), { code: "NOT_FOUND" });
  const copiedFile = await files.copy(context, moved.path, root);
  assert.equal(copiedFile.path, `${root}/renamed-Copy1.txt`);
  await files.delete(context, `${root}/dir/child`);
  await files.delete(context, `${root}/dir`);
  await assert.rejects(files.create(context, { path: moved.path, type: "file" }), { code: "CONFLICT" });
  await assert.rejects(files.rename(context, moved.path, copiedFile.path), { code: "CONFLICT" });
  await assert.rejects(files.delete(context, "/"), { code: "INVALID_REQUEST" });
  console.log(JSON.stringify({ check: "file-operations", status: "PASS", root }));
}
