import assert from "node:assert/strict";
import { readFile, utimes, writeFile } from "node:fs/promises";
import { join } from "node:path";

export async function checkWorkspaceFiles({ sessionId: worker, post, cwd, api }) {
  assert.equal((await post(worker, "files/list", {})).path, "work", "Absolute worker cwd resolves through the public Jupyter path API");
  assert.equal((await post(worker, "files/list", { path: "" })).path, "");
  await post(worker, "files/create", { path: "work/docs", type: "directory" });
  await post(worker, "files/create", { path: "work/docs/hello.txt", type: "file", content: "before\n" });
  const listing = await post(worker, "files/list", { path: "work/docs" });
  assert.equal(listing.entries.find((entry) => entry.name === "hello.txt").size, 7);
  const first = await post(worker, "files/read", { path: "work/docs/hello.txt" });
  assert.equal(first.content, "before\n");
  assert.equal(first.format, "text");
  assert.equal(first.writable, true);
  assert.equal(first.mimetype, "text/plain");
  const saved = await post(worker, "files/write", { path: first.path, content: "saved\n", format: "text", expectedLastModified: first.last_modified });
  assert.equal(await readFile(join(cwd, "docs/hello.txt"), "utf8"), "saved\n");
  await writeFile(join(cwd, "docs/hello.txt"), "agent edit\n");
  await utimes(join(cwd, "docs/hello.txt"), new Date(), new Date(Date.now() + 2000));
  const changed = await post(worker, "files/read", { path: first.path });
  const conflict = await post(worker, "files/write", { path: first.path, content: "stale\n", format: "text", expectedLastModified: saved.last_modified }, 409);
  assert.equal(conflict.code, "CONFLICT");
  assert.equal(conflict.details.last_modified, changed.last_modified);
  assert.equal(await readFile(join(cwd, "docs/hello.txt"), "utf8"), "agent edit\n");
  await post(worker, "files/create", { path: first.path, type: "file" }, 409);
  await post(worker, "files/rename", { path: first.path, newPath: "work/docs/moved.txt" });
  assert.equal((await post(worker, "files/read", { path: "work/docs/moved.txt" })).content, "agent edit\n");
  assert.equal((await post(worker, "files/copy", { path: "work/docs/moved.txt", toDir: "work/docs" })).path, "work/docs/moved-Copy1.txt", "Same-directory copy gets a -CopyN name");
  assert.equal((await post(worker, "files/copy", { path: "work/docs/moved.txt", toDir: "work" })).path, "work/moved.txt", "Copy into another directory keeps the name");
  assert.equal((await post(worker, "files/copy", { path: "work/docs", toDir: "work" })).path, "work/docs-Copy1");
  assert.equal(await readFile(join(cwd, "docs-Copy1/moved-Copy1.txt"), "utf8"), "agent edit\n", "Directories copy recursively");
  await post(worker, "files/copy", { path: "work/docs/moved.txt", toDir: "../escape" }, 400);
  await post(worker, "files/delete", { path: "work/docs/moved-Copy1.txt" });
  await post(worker, "files/create", { path: "work/binary.bin", type: "file", content: "AP+A", format: "base64" });
  const binary = await post(worker, "files/read", { path: "work/binary.bin" });
  assert.equal(binary.format, "base64");
  assert.deepEqual(Buffer.from(binary.content, "base64"), Buffer.from([0, 255, 128]));
  await post(worker, "files/write", { path: binary.path, content: binary.content, format: binary.format });
  assert.deepEqual(await readFile(join(cwd, "binary.bin")), Buffer.from([0, 255, 128]));
  await writeFile(join(cwd, "small.ipynb"), '{"cells":[],"metadata":{},"nbformat":4,"nbformat_minor":5}');
  assert.equal((await post(worker, "files/read", { path: "work/small.ipynb" })).format, "text");
  await writeFile(join(cwd, "too-big.txt"), "x".repeat(129));
  assert.equal((await post(worker, "files/read", { path: "work/too-big.txt" }, 413)).code, "TOO_LARGE");
  await post(worker, "files/delete", { path: "work/docs/moved.txt" });
  await post(worker, "files/delete", { path: "work/docs" });
  await post(worker, "files/read", { path: "work/docs/moved.txt" }, 404);
  await post(worker, "files/delete", { path: "" }, 400);
  await post(worker, "files/read", { path: "../escape" }, 400);
  assert.equal((await post("missing-session", "files/list", {}, 404)).code, "NOT_FOUND");
  const crossOrigin = await fetch(api(worker, "files/list"), { method: "POST", headers: { "Content-Type": "application/json", Origin: "https://foreign.invalid" }, body: "{}" });
  assert.equal(crossOrigin.status, 403);

}
