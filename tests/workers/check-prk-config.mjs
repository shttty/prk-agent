import { parse, stringify } from "smol-toml";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { ModelRuntime } from "@earendil-works/pi-coding-agent";
import { fauxAssistantMessage, fauxProvider, fauxToolCall } from "@earendil-works/pi-ai";
import { loadPrkConfig } from "../../src/config/document/load-prk-config.ts";
import { parsePrkConfig } from "../../src/config/document/parse-prk-config.ts";
import { prkPaths } from "../../src/config/home/resolve-prk-paths.ts";
import { resolvePrkHome } from "../../src/config/home/resolve-prk-home.ts";
import { createGatewayHost } from "../../src/gateway/host/start-host.ts";
import { prepareGatewayEnvironment } from "../fixtures/prepare-gateway-environment.mjs";
import { startGateway } from "../../src/gateway/socket-server/start-listener.ts";
import { connectGateway } from "../../src/gateway/socket-client/connect-client.ts";
import { connectWebGateway } from "../../src/http/gateway-connection/connect-gateway.ts";
import { startWebServer } from "../../src/http/listener/start-listener.ts";
import { checkConfigOptions } from "./config/check-options.mjs";

const root = await mkdtemp(join(tmpdir(), "prk-config-check-"));
const path = join(root, "config.toml");
const instancesPath = join(root, "instances.toml");
const run = promisify(execFile);
let host, gateway, adapter, web;
try {
  const env = { HOME: root };
  assert.equal(resolvePrkHome(undefined, env), join(root, ".config", "pi-remote-kernel"));
  assert.equal(resolvePrkHome(undefined, { ...env, XDG_CONFIG_HOME: join(root, "xdg") }), join(root, "xdg", "pi-remote-kernel"));
  assert.equal(resolvePrkHome(undefined, { ...env, XDG_CONFIG_HOME: "" }), join(root, ".config", "pi-remote-kernel"));
  assert.equal(resolvePrkHome(undefined, { ...env, XDG_CONFIG_HOME: "relative" }), join(root, ".config", "pi-remote-kernel"));
  assert.equal(resolvePrkHome(undefined, { ...env, PRK_HOME: join(root, "env") }), join(root, "env"));
  assert.equal(resolvePrkHome(root, { ...env, PRK_HOME: join(root, "wrong") }), root);
  assert.deepEqual(prkPaths(root), { home: root, configPath: path, instancesPath, agentDir: join(root, "agent") });
  const defaults = await loadPrkConfig(root);
  checkConfigOptions(defaults);
  for (const [key, expected] of Object.entries({ commandOutputLimitBytes: 16 * 1024 * 1024, truncatedHeadBytes: 4096, truncatedTailBytes: 4096, historyBytes: 64 * 1024 * 1024 })) {
    assert.equal(defaults.terminal[key], expected);
    assert.equal(parsePrkConfig({ terminal: { [key]: 123 } }).terminal[key], 123);
    assert.equal(parsePrkConfig({ terminal: { [key]: Number.MAX_SAFE_INTEGER } }).terminal[key], Number.MAX_SAFE_INTEGER);
    for (const value of [null, 0, -1, 1.5, "4096", true, [], {}, Number.MAX_SAFE_INTEGER + 1]) {
      assert.throws(() => parsePrkConfig({ terminal: { [key]: value } }), new RegExp(`terminal\\.${key}.*safe integer`));
    }
  }
  assert.equal(defaults.terminal.outputBrakeDefault, true);
  for (const value of [false, true]) assert.equal(parsePrkConfig({ terminal: { outputBrakeDefault: value } }).terminal.outputBrakeDefault, value);
  for (const value of [null, 0, 1, "false", [], {}]) {
    assert.throws(() => parsePrkConfig({ terminal: { outputBrakeDefault: value } }), /terminal\.outputBrakeDefault.*boolean/u);
  }
  const minimumIds = { identityChars: 44, requestIdChars: 90, operationIdChars: 73 };
  for (const [field, minimum] of Object.entries(minimumIds)) {
    assert.throws(() => parsePrkConfig({ limits: { [field]: minimum - 1 } }), new RegExp(`limits\\.${field}`), `${field} must fit identifiers generated by PRK`);
  }
  const boundedInstance = { id: "i".repeat(44), label: "Bounded", sshCommand: "TARGET=bounded /bin/sh", python: "/owned/python", cwd: "/srv/bounded" };
  assert.equal(parsePrkConfig({ limits: minimumIds }, { instances: [boundedInstance] }).instances[0].id, boundedInstance.id);
  assert.throws(() => parsePrkConfig({ limits: minimumIds }, { instances: [{ ...boundedInstance, id: `${boundedInstance.id}x` }] }), /invalid id/, "Over-limit instance identities must fail at load, not at first routed request");
  // An instance needs an absolute cwd: missing and relative ones are configuration errors.
  const { cwd: _omitted, ...withoutCwd } = boundedInstance;
  for (const instance of [withoutCwd, { ...boundedInstance, cwd: "." }, { ...boundedInstance, cwd: "relative/dir" }, { ...boundedInstance, cwd: "" }]) {
    assert.throws(() => parsePrkConfig({}, { instances: [instance] }), /requires cwd, an absolute path/);
  }
  assert.equal(parsePrkConfig({}, { instances: [boundedInstance] }).instances[0].python, "/owned/python");
  for (const python of [null, 1, "", "python3", "/python\n", "/" + "x".repeat(defaults.limits.cwdChars)]) {
    assert.throws(() => parsePrkConfig({}, { instances: [{ ...boundedInstance, python }] }), /python/);
  }
  for (const field of ["id", "label", "sshCommand", "python", "cwd", "local", "tags", "executionTimeoutMs", "capabilities", "customMetrics"]) {
    assert.throws(() => parsePrkConfig({ [field]: boundedInstance[field] }), /unsupported field/, `config.toml must reject instance field ${field}`);
  }
  for (const bad of [
    { session: null }, { session: { idleTimeoutMs: 0 } },
    { session: { askTimeoutMs: -1 } }, { session: { askTimeoutMs: 2147483648 } }, { session: { askTimeoutMs: 1.5 } },
    { session: { idleTimeoutMs: 2147483648 } },
    { kernel: { maxOutputChars: 0 } },
    { session: { defaultSendMode: "invalid" } },
    { targetConnection: { requestTimeoutMs: 0 } }, { targetConnection: { requestTimeoutMs: 1.5 } },
    { targetConnection: { startTimeoutMs: 2147483648 } }, { targetConnection: { startTimeoutMs: true } },
    { gateway: { socketPath: "relative.sock" } }, { http: { port: 65536 } },
    { gateway: { systemdUnit: "--now" } }, { gateway: { systemdUnit: "a b.service" } }, { gateway: { systemdUnit: 3 } }, { gateway: { restartTimeoutMs: 0 } },
    { limits: { socketPathBytes: 101 } }, { limits: { attachmentsMax: 1.5 } },
    { limits: { labelChars: Number.MAX_SAFE_INTEGER + 1 } }, { session: { unknown: 1 } },
    { unexpected: {} },
    { session: { workerTools: "coordination" } },
    { codemode: { unknown: 1 } },
    { codemode: { binCacheDir: " " } }, { codemode: { binCacheDir: "bin\n" } },
    { monitor: { memoryAlertPercent: 101 } }, { monitor: { memoryAlertPercent: 0 } }, { monitor: { fastIntervalMs: 0 } },
    { monitor: { enabled: "yes" } }, { monitor: { unknown: 1 } }, { monitor: { slowIntervalMs: 2147483648 } },
    { learning: null }, { learning: [] }, { learning: { unknown: true } },
  ]) assert.throws(() => parsePrkConfig(bad));

  await writeFile(path, stringify({ session: { idleTimeoutMs: 0 } }), { mode: 0o600 });
  await assert.rejects(run(process.execPath, [fileURLToPath(new URL("../../src/main.ts", import.meta.url)), "gateway", "--home", root, "--model", "offline/unavailable"], {
    cwd: root, env: { ...process.env, HOME: root, PRK_HOME: root }, timeout: 10000,
  }), (error) => error.code === 1 && /Invalid PRK configuration: session\.idleTimeoutMs/.test(error.stderr), "Invalid config must fail startup with the offending field, before SDK resources or listeners start");
  await assert.rejects(run(process.execPath, [fileURLToPath(new URL("../../src/main.ts", import.meta.url)), "gateway", "--home", "", "--model", "offline/unavailable"], {
    cwd: root, env: { ...process.env, HOME: root, PRK_HOME: root }, timeout: 10000,
  }), (error) => error.code === 1 && /Invalid PRK home/.test(error.stderr), "An invalid explicit home must produce a safe actionable startup diagnostic, not fall back to the environment");

  const document = {
    derivation: { roles: { task: { thinkingLevel: "low" } } },
    session: { idleTimeoutMs: 1200, maxMessageChars: 99 },
    kernel: { progressIntervalMs: 70 },
    learning: { autoTools: false, autoSkills: true },
    gateway: { pendingMax: 5 },
    http: { heartbeatMs: 1900 },
    terminal: { quietNotifyDefault: true, outputBrakeDefault: false, commandOutputLimitBytes: 2048, truncatedHeadBytes: 32, truncatedTailBytes: 48, historyBytes: 8192 },
    limits: { labelChars: 20, ...minimumIds },
  };
  const instanceDocument = { instances: [{ id: "fixture", label: "Before", sshCommand: "TARGET=config-fixture /bin/sh", python: "/owned/python", cwd: "/srv/config-fixture" }] };
  await writeFile(instancesPath, stringify(instanceDocument), { mode: 0o600 });
  await writeFile(path, stringify(document));
  const globalBytes = await readFile(path, "utf8");
  const config = await loadPrkConfig(root);
  assert.equal(config.terminal.quietNotifyDefault, true, "Load the terminal silence default from config.toml");
  for (const [key, value] of Object.entries(document.terminal)) assert.equal(config.terminal[key], value, `Load terminal.${key} from config.toml`);
  const runtime = await ModelRuntime.create({ authPath: join(root, "agent", "auth.json"), modelsPath: null, refreshOnCreate: false, allowModelNetwork: false });
  const provider = fauxProvider({ provider: "config-controlled", models: [{ id: "local" }], tokensPerSecond: 10000 });
  runtime.registerNativeProvider(provider.provider);
  let generatedName;
  provider.setResponses([
    () => fauxAssistantMessage(fauxToolCall("session_manage", { action: "project", session: generatedName, project: "Generated" }), { stopReason: "toolUse" }),
    fauxAssistantMessage("Project assigned"),
  ]);
  host = await createGatewayHost({ cwd: root, home: root, model: "config-controlled/local" }, {
    runtimeDependencies: { model: provider.getModel(), modelRuntime: runtime, thinkingLevel: "off", cwd: root, agentDir: join(root, "agent") },
  });
  const socket = join(root, "gateway.sock");
  gateway = await startGateway(host, socket, config.gateway, config.limits);
  adapter = await connectWebGateway({ socket, gateway: config.gateway, http: config.http, limits: config.limits });
  web = await startWebServer(adapter, { port: 0, http: config.http, limits: config.limits });
  const response = await fetch(`${web.url}/api/targets/fixture`, {
    method: "PATCH", headers: { "Content-Type": "application/json", Origin: web.url },
    body: JSON.stringify({ target: { id: "fixture", label: "After" } }),
  });
  assert.equal(response.status, 200);
  const publicResult = await response.json();
  assert.equal(publicResult.targets[0].label, "After");
  assert(!JSON.stringify(publicResult).includes(instanceDocument.instances[0].sshCommand));
  assert.equal(Object.hasOwn(publicResult.targets[0], "token"), false);
  assert.equal(await readFile(path, "utf8"), globalBytes, "Instance edits leave the global configuration byte-for-byte unchanged");
  const { instances } = structuredClone(parse(await readFile(instancesPath, "utf8")));
  assert.equal(instances[0].label, "After");
  assert.equal(instances[0].sshCommand, instanceDocument.instances[0].sshCommand, "Omitted command retains the saved original text");
  assert.equal(instances[0].python, instanceDocument.instances[0].python, "Instance editing retains the selected interpreter");
  assert.equal((await stat(instancesPath)).mode & 0o777, 0o600, "instances.toml remains owner-only");
  assert.equal((await loadPrkConfig(root)).session.maxMessageChars, 99);

  const { withTargetFixture } = await import("../fixtures/target-fixture.mjs");
  await withTargetFixture(async ({ config: target, tempRoot, onCleanup }) => {
    const projectConfig = parsePrkConfig({
      session: { workerTools: "direct", localTools: true },
    }, { instances: [{ id: "fixture", label: "Fixture", ...target, cwd: tempRoot }] });
    const projectHost = await createGatewayHost({ cwd: root, home: root, config: projectConfig, historyDir: join(root, "project-history"), model: "config-controlled/local" }, {
      runtimeDependencies: { model: provider.getModel(), modelRuntime: runtime, thinkingLevel: "off", cwd: root, agentDir: join(root, "agent") },
    });
    const projectSocket = join(root, "project-gateway.sock");
    const projectGateway = await startGateway(projectHost, projectSocket, projectConfig.gateway, projectConfig.limits);
    const client = await connectGateway(projectSocket, projectConfig.gateway, projectConfig.limits);
    onCleanup(async () => { client.disconnect(); await projectGateway.close(); });
    await prepareGatewayEnvironment(projectHost, root, "fixture");
    let unsubscribe, timer;
    try {
      const created = await client.request("createSession", { target: "fixture", cwd: tempRoot, label: "Identifier minimum" });
      generatedName = created.session.sessionId;
      await client.request("setSessionRoot", { sessionId: generatedName });
      const requestId = `derived-transfer:${generatedName}:${randomUUID()}`;
      assert.equal(requestId.length, minimumIds.requestIdChars);
      const completed = Promise.withResolvers();
      unsubscribe = client.onEvent((event, worker) => {
        if (worker === generatedName && event.type === "operation_completed" && event.details?.requestIds?.includes(requestId)) completed.resolve(event.details);
      });
      await client.request("subscribe", { sessionId: generatedName });
      const accepted = await client.request("send", { sessionId: generatedName, requestId, message: "Assign this session to the Generated project." });
      assert.equal(accepted.accepted, true);
      assert.equal(accepted.operationId.length, minimumIds.operationIdChars);
      timer = setTimeout(() => completed.reject(new Error("Minimum-ID SDK operation did not settle")), 10000);
      assert.equal((await completed.promise).status, "completed");
      clearTimeout(timer);
      const generated = (await client.request("workbench")).sessions.find((worker) => worker.sessionId === generatedName);
      assert.equal(generated.projectId.length, minimumIds.identityChars);
      await client.request("assignProject", { sessionId: generatedName, project: { id: generated.projectId, name: generated.projectName } });
      assert.equal((await client.request("cancel", { sessionId: generatedName, operationId: accepted.operationId })).status, "already_complete");
      assert.equal((await client.request("state", { sessionId: generatedName })).recentOperations.find((operation) => operation.operationId === accepted.operationId).status, "completed");
    } finally {
      clearTimeout(timer);
      unsubscribe?.();
      client.disconnect();
    }
  });
  console.log("PASS PRK config: isolated homes, validated ID boundaries, real Gateway/SDK generated project and operation IDs at minimum caps, startup rejection, and preserving HTTP instance edits");
} finally {
  try {
    await web?.close();
    await adapter?.close();
    if (gateway) await gateway.close(); else await host?.close();
  } finally { await rm(root, { recursive: true, force: true }); }
}
