import assert from "node:assert/strict";
import { createServer } from "node:http";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { setTimeout as delay } from "node:timers/promises";
import { initializePrkHome } from "../../src/config/home/initialize-prk-home.ts";
import { createSessionSettings } from "../../src/sessions/session-settings/create-settings.ts";
import { HOSTED_THEME_PATHS } from "../../src/sessions/session-settings/theme-paths.ts";
import { createHostedExtensionUI } from "../../src/sessions/extension-ui/assemble-extension-ui.ts";

assert(process.env.PI_TEST_PLUGIN_AGENT, "Use owned real package copies");
const root = await mkdtemp(join(tmpdir(), "prk-real-recall-"));
const previousHome = process.env.HOME;
process.env.HOME = root;
const home = join(root, "prk");
const { agentDir } = initializePrkHome(home);
const marker = "OWNED_RECALL_AMBER_ORCHID_731";
const query = "owned-stored-search-731";
const requests = [];
const server = createServer((request, response) => {
  requests.push(request.url);
  response.writeHead(200, { "content-type": "application/json" });
  response.end(JSON.stringify({ results: [{ title: "Owned stored result", url: "https://example.com/owned", content: "OWNED_STORED_RESULT_731" }] }));
});
let session;
let ui;
try {
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  await mkdir(agentDir, { recursive: true });
  const sources = ["@sting8k/pi-vcc", "pi-web-access"].map((name) => join(process.env.PI_TEST_PLUGIN_AGENT, "npm/node_modules", name));
  await writeFile(join(agentDir, "settings.json"), JSON.stringify({ packages: sources.map((source) => ({ source, enabled: true, location: "gateway" })), compaction: { enabled: false }, retry: { enabled: false }, defaultProjectTrust: "always" }));
  await writeFile(join(agentDir, "web-search.json"), JSON.stringify({ toolActivation: "eager", searxngBaseUrl: `http://127.0.0.1:${server.address().port}`, webSearch: { allowedProviders: ["searxng"] }, ssrf: { allowRanges: ["127.0.0.1/32"] } }));
  const { createAgentSession, DefaultResourceLoader, ModelRuntime, SessionManager } = await import("@earendil-works/pi-coding-agent");
  const { fauxProvider, fauxAssistantMessage, fauxToolCall } = await import("@earendil-works/pi-ai");
  const modelRuntime = await ModelRuntime.create({ authPath: join(agentDir, "auth.json"), modelsPath: null, refreshOnCreate: false, allowModelNetwork: false });
  const provider = fauxProvider({ provider: "owned-recall-control", models: [{ id: "controlled" }], tokensPerSecond: 100000 });
  modelRuntime.registerNativeProvider(provider.provider);
  const settingsManager = createSessionSettings(home, agentDir);
  const loader = new DefaultResourceLoader({ cwd: home, agentDir, settingsManager, noSkills: true, noContextFiles: true, additionalThemePaths: HOSTED_THEME_PATHS });
  await loader.reload();
  assert.deepEqual(loader.getExtensions().errors, []);
  const manager = SessionManager.create(home, join(root, "sessions"));
  ({ session } = await createAgentSession({ cwd: home, agentDir, settingsManager, resourceLoader: loader, modelRuntime, model: provider.getModel(), sessionManager: manager }));
  ui = await createHostedExtensionUI(session, agentDir);
  await session.bindExtensions({ uiContext: ui.context });
  assert(session.getAllTools().some(({ name }) => name === "web_search"));
  provider.setResponses([fauxAssistantMessage("Recorded owned historical content")]);
  await session.prompt(`Remember this fixture fact: ${marker}`);
  provider.setResponses([fauxAssistantMessage("Historical turn is now complete")]);
  await session.prompt("Start a later turn without the fixture fact");
  const sessionFile = manager.getSessionFile();
  assert(sessionFile && sessionFile.startsWith(root));
  assert((await readFile(sessionFile, "utf8")).includes(marker));
  provider.setResponses([fauxAssistantMessage("OWNED_RECALL_TRIGGER_TURN_COMPLETED")]);
  await session.prompt(`/pi-vcc-recall ${marker}`);
  await session.waitForIdle();
  const recalled = session.messages.findLast((message) => message.role === "custom" && message.customType === "vcc-recall");
  assert(recalled && JSON.stringify(recalled).includes(marker), JSON.stringify(session.messages));
  assert(JSON.stringify(session.messages.at(-1)).includes("OWNED_RECALL_TRIGGER_TURN_COMPLETED"));
  console.log(JSON.stringify({ proof: "original VCC command recalls actual persisted SDK history and completes triggerTurn through owned faux provider", sessionFile, recalled, final: session.messages.at(-1) }));
  provider.setResponses([fauxAssistantMessage(fauxToolCall("web_search", { queries: [query], provider: "searxng" }, { id: "owned-stored-search" }), { stopReason: "toolUse" }), fauxAssistantMessage("Stored result created")]);
  await session.prompt("Search the owned fixture endpoint");
  const result = session.messages.find((message) => message.role === "toolResult" && message.toolCallId === "owned-stored-search");
  assert(result && !result.isError && JSON.stringify(result).includes("OWNED_STORED_RESULT_731"), JSON.stringify(result));
  const browsing = session.prompt("/search");
  const dialogs = [];
  for (const expected of ["Stored Search Results", "Result "]) {
    const deadline = Date.now() + 5000;
    let prompt;
    while (!(prompt = ui.snapshot().prompts.find((entry) => entry.title?.startsWith(expected))) && Date.now() < deadline) await delay(10);
    assert(prompt, JSON.stringify(ui.snapshot()));
    dialogs.push(prompt);
    const value = expected === "Stored Search Results" ? prompt.options.find((option) => option.includes(query)) : "View details";
    assert(value, JSON.stringify(prompt));
    assert.equal((await ui.action({ operation: "dialog", id: prompt.id, value })).status, "completed");
  }
  await browsing;
  const details = ui.snapshot().notifications.findLast(({ message }) => message.includes("Queries:") && message.includes(query));
  assert(details && details.message.includes("(1 results)"), JSON.stringify(ui.snapshot()));
  assert.equal(requests.length, 1);
  console.log(JSON.stringify({ proof: "original web_search via faux model and native SDK tool execution stores results; original /search selects that result and View details displays actual query/count", result, dialogs, details, requests }));
} finally {
  if (session) await session.extensionRunner.emit({ type: "session_shutdown", reason: "quit" });
  ui?.dispose(); await session?.dispose();
  await new Promise((resolve) => server.close(resolve));
  if (previousHome === undefined) delete process.env.HOME; else process.env.HOME = previousHome;
  await rm(root, { recursive: true, force: true });
}
