import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { initializePrkHome } from "../../src/config/home/initialize-prk-home.ts";
import { parsePrkConfig } from "../../src/config/document/parse-prk-config.ts";
import { createGatewayHost } from "../../src/gateway/host/start-host.ts";
import { startGateway } from "../../src/gateway/socket-server/start-listener.ts";
import { startWebApplication } from "../../src/http/application/start-application.ts";
import { checkRegistryInstall } from "./plugin-packages/check-registry-install.mjs";
import { checkProviderSession } from "./plugin-packages/check-provider-session.mjs";

const root = await mkdtemp(join(tmpdir(), "prk-plugin-packages-"));
const previousHome = process.env.HOME;
process.env.HOME = join(root, "user");
const home = join(root, "prk");
const { agentDir } = initializePrkHome(home);
let host, gateway, web;
const model = (id) => ({ baseUrl: "http://127.0.0.1:1/v1", apiKey: "owned-unused", api: "openai-responses", models: [{ id, name: id, input: ["text"], reasoning: false, contextWindow: 4096, maxTokens: 128, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 } }] });
try {
  await mkdir(process.env.HOME, { recursive: true });
  await mkdir(agentDir, { recursive: true });
  await writeFile(join(agentDir, "models.json"), JSON.stringify({ providers: { "plugin-manual": model("manual") } }));
  await writeFile(join(agentDir, "settings.json"), "{}\n", { mode: 0o600 });
  host = await createGatewayHost({ cwd: home, home, model: "plugin-manual/manual", thinkingLevel: "off", config: parsePrkConfig({ monitor: { enabled: false }, memory: { review: false }, session: { noExtensions: false, idleTimeoutMs: 60000 } }) });
  const socket = join(home, "g.sock");
  gateway = await startGateway(host, socket);
  web = await startWebApplication({ socket, home, host: "127.0.0.1", port: 0 });
  const api = async (path, body) => {
    const response = await fetch(`${web.server.url}/api${path}`, body === undefined ? undefined : { method: "POST", headers: { "content-type": "application/json", origin: web.server.url }, body: JSON.stringify(body) });
    return { response, value: await response.json() };
  };
  assert.deepEqual((await api("/plugins")).value.packages, []);
  const source = join(root, "linked");
  await mkdir(source);
  await writeFile(join(source, "package.json"), JSON.stringify({ name: "@prk-tests/linked", version: "1.0.0", type: "module", pi: { extensions: ["index.mjs"] } }));
  await writeFile(join(source, "index.mjs"), 'export default pi => { pi.registerCommand("linked-ping", { description:"owned command", handler: async (_args,ctx) => ctx.ui.notify("linked") }); };\n');
  const installed = await api("/plugins/install", { source });
  assert.equal(installed.response.status, 200, JSON.stringify(installed.value));
  assert.equal(installed.value.packages[0].location, "gateway");
  assert.equal(installed.value.packages[0].installedPath, source);
  assert.deepEqual(installed.value.packages[0].commands, [{ name: "linked-ping", description: "owned command" }]);
  assert.equal((await stat(join(agentDir, "settings.json"))).mode & 0o777, 0o600);
  assert.equal((await api("/plugins/change", { source, enabled: false })).value.packages[0].enabled, false);
  assert.equal((await api("/plugins/change", { source, enabled: true })).value.packages[0].enabled, true);
  const hosted = await api("/plugins/change", { source, location: "host" });
  assert.equal(hosted.response.status, 200, JSON.stringify(hosted.value));
  assert.equal(hosted.value.packages[0].location, "host", "saving placement does not require an instance to exist yet");
  assert.equal((await api("/plugins/uninstall", { source })).response.status, 400);
  assert.deepEqual((await api("/plugins/uninstall", { source, confirm: true })).value.packages, []);
  assert.match(await readFile(join(source, "index.mjs"), "utf8"), /linked-ping/, "uninstall never deletes linked source");
  for (const route of ["/remote-extensions", "/remote-extensions/install", "/remote-extensions/upload"]) assert.equal((await fetch(`${web.server.url}/api${route}`)).status, 404);
  assert.equal((await api("/plugins?instance=local")).response.status, 400);
  const provider = join(root, "provider");
  await mkdir(provider);
  await writeFile(join(provider, "package.json"), JSON.stringify({ name: "@prk-tests/provider", version: "1.0.0", type: "module", pi: { extensions: ["index.mjs"] } }));
  await writeFile(join(provider, "index.mjs"), `export default pi => pi.registerProvider("plugin-owned", ${JSON.stringify(model("owned"))});\n`);
  const owner = await api("/plugins/install", { source: provider, location: "gateway" });
  assert.equal(owner.response.status, 200, JSON.stringify(owner.value));
  assert.deepEqual(owner.value.packages[0].providerIds, ["plugin-owned"]);
  assert.equal(owner.value.restartRequired, true, "newly identified provider waits for Gateway restart");
  assert(!(await host.modelCatalog()).models.some((model) => model.value === "plugin-owned/owned"));
  const refused = await api("/plugins/change", { source: provider, location: "host" });
  assert.equal(refused.value.code, "PROVIDER_POLICY", JSON.stringify(refused.value));
  assert.equal(refused.value.details.providerErrors[0].providerId, "plugin-owned");
  assert.equal(JSON.parse(await readFile(join(agentDir, "settings.json"), "utf8")).packages[0].location, "gateway");
  await api("/plugins/uninstall", { source: provider, confirm: true });
  await checkRegistryInstall(root, api);
  await checkProviderSession(root);
  console.log("PASS plugin packages: real HTTP CRUD, direct local source, native npm install, provider bootstrap/ownership, 0600, strict old route removal");
} finally {
  await web?.close();
  if (gateway) await gateway.close(); else await host?.close();
  if (previousHome === undefined) delete process.env.HOME; else process.env.HOME = previousHome;
  await rm(root, { recursive: true, force: true });
}
