import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createReadToolDefinition, DefaultResourceLoader, SessionManager, SettingsManager } from "@earendil-works/pi-coding-agent";
import { SkillLibrary } from "../../src/sessions/skill-library/assemble-skill-library.ts";
import { parsePrkConfig } from "../../src/config/document/parse-prk-config.ts";

const home = await mkdtemp(join(tmpdir(), "prk-skill-lifecycle-"));
let clock = Date.parse("2026-01-01T00:00:00Z");
const options = parsePrkConfig({ skills: { staging: { capacity: 2, idleDays: 2 }, promoted: { capacity: 1, idleDays: 2 }, promotion: { distinctSessions: 2 }, archive: { capacity: 2 } } }).skills;
try {
  for (const skills of [null, { unknown: 1 }, { staging: null }, { staging: { capacity: 0 } }, { promoted: { idleDays: 1.5 } }, { promotion: { distinctSessions: -1 } }, { archive: { capacity: Number.MAX_SAFE_INTEGER + 1 } }, { versionsKept: 2 }]) assert.throws(() => parsePrkConfig({ skills }));
  assert.equal(parsePrkConfig({}).session.noSkills, false);
  const library = new SkillLibrary(home, options, () => clock);
  const create = (name) => library.manage({ action: "create", name, scope: "global", description: `Native ${name} workflow.`, whenToUse: "Testing shared workflow.", evidence: "Fixture observed a deterministic completed run.", procedure: ["Inspect the actual result."], pitfalls: [], verification: [] });
  const entry = (name) => library.list().find((item) => item.name === name);
  const native = async () => {
    const loader = new DefaultResourceLoader({ cwd: home, agentDir: join(home, "agent"), settingsManager: SettingsManager.inMemory({}), noExtensions: true, noSkills: true, noContextFiles: true, noThemes: true, noPromptTemplates: true, additionalSkillPaths: library.paths() });
    await loader.reload();
    assert.deepEqual(loader.getSkills().diagnostics, []);
    return loader.getSkills().skills;
  };
  create("one");
  assert.throws(() => create("one"), /one.*already exists.*patch/, "An active exact name must be patched, not created again");
  for (let index = 0; index < 4; index++) await native();
  assert.equal(entry("one").distinctSessions, 0, "Repeated native discovery never counts as a body read");
  assert.equal(entry("one").lastUsedAt, undefined);
  assert.equal(entry("one").status, "staging");
  const read = async (name, session = SessionManager.inMemory(home)) => {
    const path = (await native()).find((skill) => skill.name === name).filePath;
    await createReadToolDefinition(home).execute(crypto.randomUUID(), { path });
    library.recordRead(path, session.getSessionId());
  };
  const firstSession = SessionManager.inMemory(home);
  await read("one", firstSession);
  const firstReadAt = entry("one").lastUsedAt;
  clock += 1000;
  await read("one", firstSession);
  assert.equal(entry("one").distinctSessions, 1, "Repeated successful body reads in one native session count once");
  assert(entry("one").lastUsedAt > firstReadAt, "A repeated session read refreshes the last-read timestamp");
  assert.equal(entry("one").status, "staging");
  await read("one");
  assert.equal(entry("one").status, "promoted");
  library.change("promote", "one");
  create("two");
  await read("two");
  await read("two");
  assert.equal(entry("two").status, "staging", "Manual promotion occupies the only promoted slot");
  assert.throws(() => library.change("promote", "two"), (error) => error.code === "BUSY");
  library.change("demote", "one");
  assert.equal(entry("one").status, "staging");
  assert.equal(entry("two").status, "promoted", "Pending automatic candidate gets the freed slot");
  clock += 2 * 86_400_000;
  assert.equal(entry("one").status, "archived");
  assert.equal(entry("two").status, "staging", "Idle automatic promotion is demoted before its next staging interval");
  library.change("restore", "one");
  library.change("promote", "one");
  clock += 4 * 86_400_000;
  assert.equal(entry("one").status, "promoted", "Manual promotion is immune to idle aging");
  library.manage({ action: "patch", name: "one", section: "procedure", value: ["Inspect the updated workflow."] });
  assert.equal(entry("one").manual, true, "Editing keeps human promotion");
  library.change("archive", "one");
  assert.throws(() => create("one"), /one.*already exists.*patch.*restoring/, "An archived exact name remains reserved until deletion");
  assert.equal(entry("one").manual, false);
  assert(!(await native()).some((skill) => skill.name === "one"), "Native loader receives no archived paths");
  assert.throws(() => library.readPath(join(home, "skills/one/SKILL.md")), /Archived/);
  library.change("restore", "one");
  assert.equal(entry("one").status, "staging");
  assert((await native()).some((skill) => skill.name === "one"));
  library.change("delete", "one");
  assert(!entry("one"));
  assert.throws(() => library.change("restore", "one"), (error) => error.code === "NOT_FOUND");
  create("hidden");
  const hiddenPath = join(home, "skills/hidden/SKILL.md");
  await writeFile(hiddenPath, (await readFile(hiddenPath, "utf8")).replace("---\n\n", "disable-model-invocation: true\n---\n\n"));
  await native();
  assert.equal(entry("hidden").distinctSessions, 0, "Hidden skill discovery is not a body read");
  assert.equal(entry("hidden").lastUsedAt, undefined);
  await read("hidden");
  assert.equal(entry("hidden").distinctSessions, 1, "An actual read counts even when model advertisement is disabled");
  create("three");
  create("four");
  assert.equal(entry("three").status, "archived", "Staging overflow archives an unread skill before a hidden skill with an actual read");
  create("five");
  create("six");
  assert(library.list().filter((item) => item.status === "archived").length <= 2);
  const persisted = new SkillLibrary(home, options, () => clock);
  assert.deepEqual(persisted.list(), library.list(), "Lifecycle metadata and native files survive recreation");
  console.log("PASS shared native skills: configured promotion, distinct successful-read sessions, repeated-read timestamp, manual immunity, idle demotion/archive, capacities, restore/delete, hidden reads, persistence");
} finally { await rm(home, { recursive: true, force: true }); }
