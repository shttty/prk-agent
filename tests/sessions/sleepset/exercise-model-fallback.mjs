import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";
import { withSleepSettingsFixture } from "./assemble-fixture.mjs";

const previousModel = "sleepset/removed", model = "sleepset/primary";
await withSleepSettingsFixture(async (f) => {
  const asleep = await f.create("Unavailable model repaired before wake");
  const acknowledged = await f.create("Unavailable model acknowledged");
  const changed = await f.create("Unavailable model changed explicitly");
  assert.equal(Object.hasOwn(await f.state(asleep), "modelFallback"), false, "Normal full snapshots omit fallback state");
  await f.change(acknowledged, "thinking", { level: "high" });
  await f.stop();
  for (const sessionId of [asleep, acknowledged, changed]) await f.markUnavailable(sessionId, previousModel);
  await f.start();
  const calls = f.provider.requests.length, kernels = await f.kernels();
  assert.equal((await f.state(asleep)).model, previousModel, "An unawakened snapshot does not invent a completed fallback");
  assert.deepEqual(await f.change(asleep, "model", { model: "sleepset/alternate" }), { model: "sleepset/alternate", thinkingLevel: "off" });
  const repaired = await f.state(asleep);
  assert.equal(repaired.state, "sleeping");
  assert.equal(repaired.model, "sleepset/alternate");
  assert.equal(Object.hasOwn(repaired, "modelFallback"), false, "Repairing asleep avoids fallback entirely");
  assert.deepEqual(await f.kernels(), kernels);
  assert.equal(f.provider.requests.length, calls);
  await f.send(asleep, "FALLBACK_REPAIRED_ASLEEP");
  assert.equal(f.provider.requests[calls].model, "alternate");
  const fallback = async (sessionId) => {
    const before = f.provider.requests.length;
    await f.request("wakeSession", { sessionId });
    assert.equal(f.provider.requests.length, before, "Wake does not submit a model request");
    const snapshot = await f.state(sessionId);
    assert.equal(snapshot.sessionId, sessionId);
    assert.equal(snapshot.model, model);
    assert.equal(snapshot.modelFallback?.previousModel, previousModel);
    assert.equal(snapshot.modelFallback?.model, model);
    assert.equal(typeof snapshot.modelFallback.reason, "string");
    assert(snapshot.modelFallback.reason.length > 0);
    const entries = await f.entries(sessionId), models = entries.filter(({ type }) => type === "model_change");
    assert.equal(models.at(-2).modelId, "removed");
    assert.deepEqual({ provider: models.at(-1).provider, modelId: models.at(-1).modelId }, { provider: "sleepset", modelId: "primary" }, "SDK native model_change writes back the actual default");
    return { snapshot, nativeCount: models.length };
  };
  const first = await fallback(acknowledged), defaultOffset = f.provider.requests.length;
  await f.send(acknowledged, "FALLBACK_DEFAULT_SEND");
  assert.equal(f.provider.requests[defaultOffset].model, "primary", "Actual first HTTP request agrees with the snapshot and native file");
  assert.equal(f.provider.requests[defaultOffset].reasoning?.effort, "high");
  assert.deepEqual((await f.state(acknowledged)).modelFallback, first.snapshot.modelFallback, "Sending does not silently dismiss the notice");
  await f.until(() => f.host.state(acknowledged).state === "sleeping", "fallback session naturally sleeps");
  assert.deepEqual((await f.state(acknowledged)).modelFallback, first.snapshot.modelFallback, "Notice survives sleeping in the current Gateway process");
  await f.request("wakeSession", { sessionId: acknowledged });
  assert.deepEqual((await f.state(acknowledged)).modelFallback, first.snapshot.modelFallback);
  assert.equal((await f.entries(acknowledged)).filter(({ type }) => type === "model_change").length, first.nativeCount, "Second wake does not repeat the persisted fallback");
  await f.until(() => f.host.state(acknowledged).state === "sleeping", "acknowledgement can occur asleep");
  const beforeAck = await f.entries(acknowledged);
  await f.request("subscribe", { sessionId: acknowledged });
  const ackEvents = f.events.length;
  await f.change(acknowledged, "acknowledge-model-fallback", {});
  assert.equal((await f.state(acknowledged)).state, "sleeping");
  assert.equal(Object.hasOwn(await f.state(acknowledged), "modelFallback"), false);
  assert.deepEqual(await f.entries(acknowledged), beforeAck, "Acknowledgement is a current-process notice, not new session storage");
  await f.until(() => f.events.slice(ackEvents).some(({ sessionId, event }) => sessionId === acknowledged && event.type === "snapshot"
    && event.details?.snapshot && !Object.hasOwn(event.details.snapshot, "modelFallback")), "acknowledgement pushes authoritative absence");
  const second = await fallback(changed);
  assert.equal((await f.action(changed, "model", { model: "sleepset/absent" })).status, "failed");
  assert.deepEqual((await f.state(changed)).modelFallback, second.snapshot.modelFallback, "Failed selection cannot dismiss a real fallback");
  await f.request("subscribe", { sessionId: changed });
  assert.deepEqual(await f.change(changed, "model", { model: "sleepset/plain" }), { model: "sleepset/plain", thinkingLevel: "off" });
  assert.equal(Object.hasOwn(await f.state(changed), "modelFallback"), false, "Explicit valid model selection dismisses the notice");
  const explicitOffset = f.provider.requests.length;
  await f.send(changed, "FALLBACK_EXPLICIT_MODEL");
  assert.equal(f.provider.requests[explicitOffset].model, "plain");
  assert.equal(f.provider.requests[explicitOffset].reasoning, undefined);
  await f.stop();
  await f.start();
  assert.equal((await f.state(asleep)).model, "sleepset/alternate");
  assert.equal((await f.state(acknowledged)).model, model);
  assert.equal((await f.state(changed)).model, "sleepset/plain");
  await f.request("wakeSession", { sessionId: acknowledged });
  assert.equal(Object.hasOwn(await f.state(acknowledged), "modelFallback"), false, "Persisted default reopens without repeating fallback");
  assert.equal((await f.entries(acknowledged)).filter(({ type }) => type === "model_change").length, first.nativeCount);
  await f.evidence("unavailable-model.json", { first: first.snapshot, second: second.snapshot, requests: f.provider.requests.slice(calls) });
  await writeFile(process.env.PI_TEST_SLEEPSET_FALLBACK_RESULT, JSON.stringify({ previousModel, model, fallbackCount: 2 }));
}, { idleTimeoutMs: 800 });
