import assert from "node:assert/strict";

export async function checkSleepingPayload(f, sessionId) {
  const native = ["bash", "edit", "find", "grep", "ls", "read", "write"];
  await f.stop();
  await f.start();
  const sleeping = await f.state(sessionId);
  assert.equal(sleeping.state, "sleeping");
  assert.equal(sleeping.model, "sleepset/alternate");
  assert.equal(sleeping.thinkingLevel, "high");
  assert.equal(sleeping.toolMode, "direct");
  assert.equal(sleeping.delegation, "eager");
  const offset = f.provider.requests.length;
  await f.request("wakeSession", { sessionId });
  assert.equal(f.provider.requests.length, offset, "Wake itself does not contact any provider");
  const current = (await f.request("nativeCapabilities", { sessionId })).target.current;
  assert.equal(current.localTools, true, "Local-tools override is restored, not the configured false default");
  assert.deepEqual(current.scopedModels, ["sleepset/alternate", "sleepset/primary"]);
  const catalog = await f.change(sessionId, "capabilities", {});
  assert.equal(catalog.entries.find(({ id }) => id === "tool:ask").enabled, false);
  await f.send(sessionId, `PROMPT_OPERATION ${JSON.stringify({ tool: "kernel_code", args: { code: "print('SLEEPSET_REAL_KERNEL')" } })}`);
  const direct = f.provider.requests[offset];
  assert(direct, "Observe the very first serialized HTTP request after wake");
  assert.equal(direct.model, "alternate");
  assert.equal(direct.reasoning?.effort, "high");
  const declarations = direct.tools.map(({ name }) => name).sort();
  for (const name of [...native, "kernel_code", "session_spawn"]) assert(declarations.includes(name), `Restored direct/native declaration: ${name}`);
  assert(!declarations.includes("ask"), "Sleeping capability disable reaches the first provider request");
  const result = (await f.state(sessionId)).messages.findLast((message) => message.role === "toolResult" && message.toolName === "kernel_code");
  assert(result, "The provider's tool call executes through real SDK and Jupyter");
  assert.equal(result.isError, false);
  assert.match(JSON.stringify(result.content), /SLEEPSET_REAL_KERNEL/);
  await f.stop();
  await f.start();
  await f.change(sessionId, "tool-mode", { mode: "code" });
  await f.change(sessionId, "local-tools", { enabled: false });
  await f.change(sessionId, "capabilities", { changes: [{ id: "tool:ask", enabled: true }] });
  assert.equal((await f.state(sessionId)).state, "sleeping");
  const nextOffset = f.provider.requests.length;
  await f.send(sessionId, "SLEEPSET_AUTOWAKE_CODE");
  const code = f.provider.requests[nextOffset];
  assert.equal(code.model, "alternate");
  assert.equal(code.reasoning?.effort, "high");
  assert.deepEqual(code.tools.map(({ name }) => name).sort(), ["kernel_code", "kernel_interrupt", "kernel_read"], "Sleeping mode/native edits reach automatic wake's first provider request");
  assert.equal((await f.state(sessionId)).delegation, "eager");
  return { direct, code };
}
