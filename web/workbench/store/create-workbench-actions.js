import { getJson } from "./requests/get-json.js";
import { requestJson } from "./requests/request-json.js";

export function createWorkbenchActions(ctx) {
  return {
    start: ctx.bound.start,
    designateRole: ctx.bound.designateRole,
    reloadTargets: ctx.bound.reloadTargets,
    selectSession: ctx.bound.selectSession,
    extensionUiAction: ctx.bound.extensionUiAction,
    requestExtensionUiRender: ctx.bound.requestExtensionUiRender,
    loadToolContent: ctx.bound.loadToolContent,
    loadTranscriptContent: ctx.bound.loadTranscriptContent,
    loadHistoryPage: ctx.bound.loadHistoryPage,
    nativeData: ctx.bound.nativeData,
    executeNativeAction: ctx.bound.executeNativeAction,
    forkMessage: ctx.bound.forkMessage,
    rerunMessage: ctx.bound.rerunMessage,
    cancelNativeAction: ctx.bound.cancelNativeAction,
    loadReferenceCandidates: ctx.bound.loadReferenceCandidates,
    clearReferenceCandidates: ctx.bound.clearReferenceCandidates,
    setAttachments: ctx.bound.setAttachments,
    setReferences: ctx.bound.setReferences,
    setDraft: ctx.bound.setDraft,
    setQueue: ctx.bound.setQueue,
    setViewMode: ctx.bound.setViewMode,
    savePresentation: ctx.bound.savePresentation,
    noteScroll: ctx.bound.noteScroll,
    flushScroll: ctx.bound.flushScroll,
    clearError: ctx.bound.clearError,
    clearNotice: ctx.bound.clearNotice,
    sendMessage: ctx.bound.sendMessage,
    cancelOperation: ctx.bound.cancelOperation,
    reconnect: ctx.bound.reconnect,
    createSession: ctx.bound.createSession,
    renameSession: ctx.bound.renameSession,
    manageSession: ctx.bound.manageSession,
    assignProject: ctx.bound.assignProject,
    renameProject: (projectId, name) => requestJson(ctx, `${ctx.apiRoot}/projects/${encodeURIComponent(projectId)}/rename`, { method: "POST", body: JSON.stringify({ name }) }),
    archiveSession: ctx.bound.archiveSession,
    archivePreview: ctx.bound.archivePreview,
    archiveProjectPreview: ctx.bound.archiveProjectPreview,
    archiveProject: ctx.bound.archiveProject,
    unarchive: ctx.bound.unarchive,
    purgeArchive: ctx.bound.purgeArchive,
    recoverSession: ctx.bound.recoverSession,
    wakeSession: ctx.bound.wakeSession,
    getTarget: ctx.bound.getTarget,
    inspectTarget: ctx.bound.inspectTarget,
    browseTarget: ctx.bound.browseTarget,
    saveTarget: ctx.bound.saveTarget,
    deleteTarget: ctx.bound.deleteTarget,
    deployEnvironment: ctx.bound.deployEnvironment,
    // Raw same-origin /api access for workbench panels (files, terminals, kernel, tools).
    // Errors carry .code/.details/.status from the backend body.
    api: {
      root: ctx.apiRoot,
      get: (path) => getJson(ctx, `${ctx.apiRoot}${path}`),
      post: ctx.bound.postSettled,
      upload: (path, file) => requestJson(ctx, `${ctx.apiRoot}${path}`, { method: "POST", headers: { "Content-Type": "application/octet-stream" }, body: file }),
    },
  };
}
